const { chromium } = require("playwright-core");
const fs = require("fs");
const BASE = process.argv[2] || "http://127.0.0.1:18431";
const path = require("path");
const SHOTS = process.argv[3] || process.env.SHOTS || path.join(__dirname, "shots");
fs.mkdirSync(SHOTS, { recursive: true });
let fails = 0;
const ok = (c, m) => { console.log((c ? "OK " : "BAD ") + m); if (!c) fails++; };
const ALLOWED = /^https:\/\/(www\.ncsc\.gov\.uk\/|learn\.microsoft\.com\/en-us\/|www\.linkedin\.com\/company\/102617034\/$|github\.com\/nusairi\/govassure$|www\.govassured\.com\/$)/;
(async () => {
  const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
  const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
  const page = await ctx.newPage();
  const errs = [];
  page.on("console", m => { if (m.type() === "error" || /Content Security Policy/i.test(m.text())) errs.push(m.text()); });
  page.on("pageerror", e => errs.push("pageerror " + e.message));
  page.on("dialog", d => d.accept());
  await page.addInitScript(() => { window.__csp = []; document.addEventListener("securitypolicyviolation", e => window.__csp.push(e.violatedDirective + " " + e.blockedURI)); });
  const resp = await page.goto(BASE + "/matrix/game", { waitUntil: "networkidle" });
  ok(resp.status() === 200, "GET /matrix/game " + resp.status());
  const h = resp.headers();
  ok(/default-src 'none'/.test(h["content-security-policy"] || "") && h["x-frame-options"] === "DENY", "CSP and security headers on game");
  ok(await page.$eval('meta[name="robots"]', m => m.content) === "noindex,nofollow", "game is noindex");
  ok(/Guard the building/.test(await page.textContent(".g-title")), "title screen");
  // setup: 3 teams, rename, timer off
  await page.click("button[data-teams='3']");
  ok(await page.locator(".g-name input").count() === 3, "team count set to 3");
  await page.fill("#gTeam0", "Owls");
  await page.fill("#gTeam2", "Hedgehogs");
  await page.click("button[data-per='6']");
  await page.screenshot({ path: SHOTS + "/game-title.png" });
  await page.reload({ waitUntil: "networkidle" });
  ok(await page.inputValue("#gTeam0") === "Owls" && await page.locator(".g-name input").count() === 3, "team names and count persist after reload");
  // keyboard-only start: focus Start and press Enter
  await page.focus("#gStart"); await page.keyboard.press("Enter");
  ok((await page.textContent("#gWhere")) === "Round 1", "Enter on Start opens round 1 intro");
  ok(await page.locator(".g-floor").count() === 9, "intro shows the nine-floor building");
  await page.screenshot({ path: SHOTS + "/game-round1-intro.png" });
  await page.keyboard.press("PageDown");
  ok(/Round 1 · 1\/6/.test(await page.textContent("#gWhere")), "PageDown (clicker) moves to card 1");
  ok(await page.locator(".g-grid--layers .g-opt").count() === 10 && await page.locator(".g-opt.is-right").count() === 0, "10 layer choices, answer hidden");
  ok((await page.textContent("#gNext")).includes("Reveal"), "Next button says Reveal before the answer");
  await page.screenshot({ path: SHOTS + "/game-card.png" });
  await page.keyboard.press("ArrowRight");
  ok(await page.locator(".g-opt.is-right").count() === 1 && /L1/.test(await page.textContent(".g-opt.is-right")), "first press reveals: right answer L1 highlighted");
  ok(await page.locator(".g-opt.is-near").count() >= 1 && await page.isVisible("#gWhy"), "near answer and plain explanation shown");
  // scoring
  await page.keyboard.press("1");
  await page.keyboard.press("Shift+2");
  await page.click(".g-award__t:nth-of-type(3) .g-pt >> nth=0");
  await page.click(".g-award__t:nth-of-type(3) .g-pt >> nth=0");
  const minis = async () => (await page.$$eval("#gMini b", b => b.map(x => +x.textContent))).join(",");
  ok(await minis() === "2,1,0", "scores: key 1 = +2, Shift+2 = +1, clicking twice toggles off (" + await minis() + ")");
  await page.keyboard.press("4");
  ok(await minis() === "2,1,0", "key for a team that is not playing is ignored");
  await page.screenshot({ path: SHOTS + "/game-reveal.png" });
  await page.reload({ waitUntil: "networkidle" });
  ok(/1\/6/.test(await page.textContent("#gWhere")) && await page.locator(".g-opt.is-right").count() === 1 && await minis() === "2,1,0", "step, reveal and scores persist after reload");
  // skip and back
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("s");
  ok(/3\/6/.test(await page.textContent("#gWhere")), "S skips a card");
  await page.keyboard.press("ArrowLeft");
  ok(/2\/6/.test(await page.textContent("#gWhere")) && await page.locator(".g-opt.is-right").count() === 0 && /Skipped/.test(await page.textContent(".g-hint")), "back to skipped card: still hidden, marked skipped");
  await page.keyboard.press("r");
  ok(await page.locator(".g-opt.is-right").count() === 1, "R reveals a skipped card");
  // to half time
  for (let i = 0; i < 20 && (await page.textContent("#gWhere")) !== "Half time"; i++) await page.keyboard.press("PageDown");
  ok((await page.textContent("#gWhere")) === "Half time", "reached half-time scoreboard");
  const order = await page.$$eval(".g-score__name", n => n.map(x => x.textContent));
  ok(order[0] === "Owls" && order.length === 3, "scoreboard ranks teams (" + order.join(", ") + ")");
  await page.click("button[data-bonus='2'][data-d='1']");
  ok(await minis() === "2,1,1", "bonus +1 button");
  await page.screenshot({ path: SHOTS + "/game-scoreboard.png" });
  // round 2
  await page.keyboard.press("ArrowRight");
  ok((await page.textContent("#gWhere")) === "Round 2", "round 2 intro");
  await page.keyboard.press("ArrowRight");
  ok(await page.locator(".g-grid--tools .g-opt").count() === 4 && (await page.$$eval(".g-letter", l => l.map(x => x.textContent).join(""))) === "ABCD", "round 2: four tool choices A to D");
  await page.screenshot({ path: SHOTS + "/game-round2-card.png" });
  await page.keyboard.press("ArrowRight");
  ok(/Not a Microsoft tool/.test(await page.textContent(".g-opt.is-right")), "tailgating answer: not a Microsoft tool");
  await page.keyboard.press("ArrowRight"); await page.keyboard.press("ArrowRight");
  const right2 = await page.textContent(".g-opt.is-right");
  ok(/Defender for Office 365/.test(right2), "fake invoice answer: Defender for Office 365");
  ok(await page.$eval(".g-opt.is-right .g-letter", e => e.textContent) !== "A", "right answer is not always A");
  await page.keyboard.press("3");
  ok(await minis() === "2,1,3", "round 2 award +2 to team 3");
  await page.screenshot({ path: SHOTS + "/game-round2-reveal.png" });
  // final + tools
  await page.keyboard.press("End");
  ok((await page.textContent("#gWhere")) === "Tool list", "End jumps to the tool list");
  ok(await page.locator(".g-tooltable .ms-table tbody tr").count() === 33 && await page.locator(".g-cover .ms-cover tbody tr").count() === 10, "tool list: 33 tools, 10 layer rows");
  const links = await page.$$eval(".g-screen a[href^='http']", a => a.map(x => [x.href, x.target]));
  ok(links.length > 30 && links.every(l => /^https:\/\/learn\.microsoft\.com\/en-us\//.test(l[0]) && l[1] === "_blank"), "tool links: Microsoft Learn only, new tab (" + links.length + ")");
  await page.screenshot({ path: SHOTS + "/game-final-tools.png" });
  await page.screenshot({ path: SHOTS + "/game-final-tools-full.png", fullPage: true });
  await page.keyboard.press("ArrowLeft");
  ok((await page.textContent("#gWhere")) === "Final" && /Hedgehogs win!/.test(await page.textContent(".g-win .g-h")), "final screen names the winner");
  await page.screenshot({ path: SHOTS + "/game-final-scores.png" });
  // print handout
  await page.keyboard.press("ArrowRight");
  await page.emulateMedia({ media: "print" });
  ok(await page.isVisible("#gPrintView") && !(await page.isVisible("#gMain")), "print shows only the tool list handout");
  ok(await page.locator("#gPrintView .ms-table tbody tr").count() === 33, "printed handout lists all 33 tools");
  await page.pdf({ path: SHOTS + "/game-tool-handout.pdf", landscape: true, format: "A4", printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: "screen" });
  // new game keeps names, resets scores
  await page.keyboard.press("Home");
  await page.click("#gNew");
  ok(await minis() === "0,0,0" && (await page.textContent("#gWhere")) === "Round 1", "New game resets scores");
  await page.keyboard.press("Home");
  ok(await page.inputValue("#gTeam0") === "Owls", "New game keeps team names");
  // timer
  await page.click("button[data-timer='30']");
  await page.click("#gStart"); await page.keyboard.press("ArrowRight");
  await page.waitForTimeout(2200);
  const tt = await page.textContent("#gTimer");
  ok(await page.isVisible("#gTimer") && /⏱ 2[78]s/.test(tt), "timer counts down on a card (" + tt + ")");
  await page.keyboard.press("t");
  const p1 = await page.textContent("#gTimer"); await page.waitForTimeout(1300);
  ok(p1 === await page.textContent("#gTimer") && /paused/.test(p1), "T pauses the timer");
  await page.keyboard.press("r");
  ok(await page.locator(".g-opt.is-right").count() === 1, "reveal works with the timer on");
  await page.keyboard.press("Home"); await page.click("button[data-timer='0']");
  const ext = await page.$$eval("a[href^='http']", as => as.map(a => a.href));
  ok(ext.every(u => ALLOWED.test(u)), "only allowed external links on the game page");
  ok((await page.evaluate(() => window.__csp)).length === 0, "no CSP violations on the game");
  ok(errs.length === 0, "no console errors on the game " + JSON.stringify(errs));
  // tool list page
  const tp = await ctx.newPage(); const terr = [];
  tp.on("console", m => { if (m.type() === "error") terr.push(m.text()); });
  const tr = await tp.goto(BASE + "/matrix/tools", { waitUntil: "networkidle" });
  ok(tr.status() === 200 && await tp.locator("#msTable .ms-table tbody tr").count() === 33, "GET /matrix/tools: 33 tools");
  ok(await tp.$eval('meta[name="robots"]', m => m.content) === "noindex,nofollow", "tool list is noindex");
  await tp.screenshot({ path: SHOTS + "/tools-page.png" });
  await tp.emulateMedia({ media: "print" });
  ok(await tp.isVisible("#msTable") && !(await tp.isVisible(".tut-bar")) && !(await tp.isVisible("#msPrint")), "tool list print view hides navigation and buttons");
  await tp.pdf({ path: SHOTS + "/tools-handout.pdf", landscape: true, format: "A4", printBackground: true, preferCSSPageSize: true });
  ok(terr.length === 0, "no console errors on tool list");
  // phone
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const pp = await phone.newPage(); const perr = [];
  pp.on("console", m => { if (m.type() === "error") perr.push(m.text()); });
  await pp.goto(BASE + "/matrix/game", { waitUntil: "networkidle" });
  await pp.screenshot({ path: SHOTS + "/phone-game-title.png" });
  await pp.tap("#gStart"); await pp.tap("#gNext");
  ok(await pp.evaluate(() => document.documentElement.scrollWidth) <= 392, "phone: game card fits, no sideways scroll");
  await pp.screenshot({ path: SHOTS + "/phone-game-card.png", fullPage: true });
  await pp.tap("#gNext");
  ok(await pp.locator(".g-opt.is-right").count() === 1, "phone: tap Next reveals");
  const btn = await pp.$eval(".g-pt", b => b.getBoundingClientRect().height);
  ok(btn >= 40, "phone: point buttons are big enough to tap (" + Math.round(btn) + "px)");
  await pp.screenshot({ path: SHOTS + "/phone-game-reveal.png", fullPage: true });
  await pp.goto(BASE + "/matrix/tools", { waitUntil: "networkidle" });
  ok(await pp.evaluate(() => document.documentElement.scrollWidth) <= 392, "phone: tool list fits");
  await pp.screenshot({ path: SHOTS + "/phone-tools.png" });
  ok(perr.length === 0, "phone: no console errors " + JSON.stringify(perr));
  await browser.close();
  console.log(fails ? "GAME-E2E-FAILED " + fails : "GAME-E2E-PASSED");
  process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(2); });
