const { chromium } = require("playwright-core");
const fs = require("fs");
const BASE = process.argv[2] || "http://127.0.0.1:18431";
const path = require("path");
const SHOTS = process.argv[3] || process.env.SHOTS || path.join(__dirname, "shots");
const TMP = "/tmp/ot-e2e"; fs.mkdirSync(TMP, { recursive: true }); fs.mkdirSync(SHOTS, { recursive: true });
let fails = 0;
const ok = (c, m) => { console.log((c ? "OK " : "BAD ") + m); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  const page = await ctx.newPage();
  const errs = [];
  page.on("console", m => { if (m.type() === "error" || /Content Security Policy/i.test(m.text())) errs.push(m.text()); });
  page.on("pageerror", e => errs.push("pageerror " + e.message));
  page.on("dialog", d => d.accept());
  await page.addInitScript(() => { window.__csp = []; document.addEventListener("securitypolicyviolation", e => window.__csp.push(e.violatedDirective + " " + e.blockedURI)); });
  const ourList = () => page.evaluate(() => JSON.parse(localStorage.getItem("ga-osi-our-tools-v1") || "[]"));

  /* ---- matrix: type your own tool ---- */
  await page.goto(BASE + "/matrix", { waitUntil: "networkidle" });
  ok(await page.locator("#mx-tool-2 option[value='__new']").count() === 1, "matrix picker has 'Type your own tool'");
  await page.selectOption("#mx-tool-2", "__new");
  ok(await page.isVisible("#otDialog"), "choosing it opens the add-tool form");
  ok(await page.isChecked("#otL2") && !(await page.isChecked("#otL5")), "the row's layer (L2) is pre-ticked");
  ok(await page.evaluate(() => document.activeElement.id) === "otName", "focus moves to the tool name");
  await page.click("#otSave");
  ok(/type the tool/i.test(await page.textContent("#otErr")), "empty name is refused with a message");
  await page.fill("#otName", "Identity Services Engine (ISE)");
  await page.fill("#otVendor", "Cisco");
  await page.fill("#otPlain", "Checks devices before they join the office network");
  await page.check("#otL5");
  const unl = await page.$$eval("#otDialog input, #otDialog textarea", els => els.filter(e => !(e.labels && e.labels.length)).length);
  ok(unl === 0, "every field in the form has a label");
  await page.screenshot({ path: SHOTS + "/add-tool-form.png" });
  await page.click("#otSave");
  ok(!(await page.isVisible("#otDialog")), "form closes on save");
  const c2 = await page.$$eval("#mx-ctls-2 textarea", t => t.map(x => x.value));
  ok(c2.includes("Identity Services Engine (ISE) (Cisco)"), "typed tool added to the L2 row");
  ok((await ourList()).length === 1 && (await ourList())[0].layers.join() === "2,5", "saved to Our tools with layers L2 and L5");
  const g5 = await page.$eval("#mx-tool-5 optgroup", g => g.label + ": " + [...g.querySelectorAll("option")].map(o => o.textContent).join("|"));
  ok(/^Our tools at L5: Identity Services Engine \(ISE\) \(Cisco\)/.test(g5), "reusable: appears first in the L5 picker (" + g5 + ")");
  ok(await page.locator("#mx-tool-7 optgroup[label='Our tools (other layers)'] option").count() === 1, "and in other rows under 'Our tools (other layers)'");
  const v = await page.$eval("#mx-tool-5 optgroup option", o => o.value);
  await page.selectOption("#mx-tool-5", v);
  ok((await page.$$eval("#mx-ctls-5 textarea", t => t.map(x => x.value))).includes("Identity Services Engine (ISE) (Cisco)"), "reused tool added to the L5 row");
  // a nasty name to check escaping and CSV guard
  await page.selectOption("#mx-tool-7", "__new");
  await page.fill("#otName", "=HYPERLINK(\"x\") <b>bold</b>");
  await page.click("#otSave");
  ok(await page.locator("#mxBody b:text('bold')").count() === 0 && (await page.$$eval("#mx-ctls-7 textarea", t => t.map(x => x.value))).includes("=HYPERLINK(\"x\") <b>bold</b>"), "tool names are treated as text, not HTML");
  await page.waitForTimeout(400);
  await page.reload({ waitUntil: "networkidle" });
  ok((await ourList()).length === 2 && (await page.$$eval("#mx-ctls-5 textarea", t => t.map(x => x.value))).includes("Identity Services Engine (ISE) (Cisco)"), "Our tools and row entries persist after reload");

  /* ---- tool list page ---- */
  await page.goto(BASE + "/matrix/tools", { waitUntil: "networkidle" });
  ok(/Which tool covers what/.test(await page.textContent("h1")) && /starter set/.test(await page.textContent(".mx-intro .lede")), "tool list framed as any vendor, Microsoft as starter set");
  ok(await page.locator("#otList tbody tr").count() === 2, "Our tools section lists the 2 typed tools");
  ok(/added by you/.test(await page.textContent("#otList")), "marked 'added by you'");
  const l2 = await page.textContent("#msCover tbody tr:nth-child(8)");
  ok(/Data Link/.test(l2) && /Identity Services Engine \(ISE\) \(Cisco\)/.test(l2) && /added by you/.test(l2), "layer-by-layer table includes our tool at L2");
  await page.click("#otSugg summary");
  await page.click("button.ot-chip:has-text('Cisco Duo')");
  ok((await ourList()).some(t => t.name === "Cisco Duo") && await page.locator("button.ot-chip[disabled]:has-text('Cisco Duo')").count() === 1, "quick-add suggestion adds Cisco Duo and marks it added");
  ok(await page.locator("#otChips button").count() >= 15, "suggestions include Cisco, Palo Alto, Fortinet, CrowdStrike, Splunk, Zscaler, Okta and more (" + await page.locator("#otChips button").count() + ")");
  // edit
  const isePos = (await page.$$eval("#otList tbody tr", r => r.map(x => x.textContent))).findIndex(t => /Identity Services/.test(t));
  await page.click(`#otList tbody tr:nth-child(${isePos + 1}) .ot-edit`);
  ok(await page.inputValue("#otName") === "Identity Services Engine (ISE)" && await page.isChecked("#otL5"), "Edit opens the form filled in");
  await page.fill("#otName", "Cisco ISE");
  await page.click("#otSave");
  ok((await ourList()).some(t => t.name === "Cisco ISE") && /Cisco ISE/.test(await page.textContent("#msCover")), "edit saves and the tables update");
  await page.screenshot({ path: SHOTS + "/tools-our-tools.png" });
  await page.screenshot({ path: SHOTS + "/tools-our-tools-full.png", fullPage: true });
  // export JSON + CSV
  let [dl] = await Promise.all([page.waitForEvent("download"), page.click("#otExportJson")]);
  await dl.saveAs(TMP + "/our.json");
  [dl] = await Promise.all([page.waitForEvent("download"), page.click("#otExportCsv")]);
  await dl.saveAs(TMP + "/our.csv");
  const json = JSON.parse(fs.readFileSync(TMP + "/our.json", "utf8"));
  const csv = fs.readFileSync(TMP + "/our.csv", "utf8");
  ok(json.type === "ga-osi-our-tools" && json.tools.length === 3, "JSON export has 3 tools");
  ok(csv.startsWith("\uFEFFTool,Vendor,What it does,Layers") && csv.includes("\"'=HYPERLINK(\"\"x\"\") <b>bold</b>\""), "CSV export has a header and guards formula-like names");
  const before = await ourList();
  const strip = l => JSON.stringify(l.map(t => [t.name, t.vendor, t.plain, t.layers]));
  // clear and import JSON
  await page.evaluate(() => localStorage.removeItem("ga-osi-our-tools-v1"));
  await page.reload({ waitUntil: "networkidle" });
  ok(await page.locator("#otList tbody tr").count() === 0, "cleared for import test");
  await page.setInputFiles("#otImport", TMP + "/our.json");
  await page.waitForFunction(() => /Imported 3 tools/.test(document.getElementById("otStatus").textContent));
  ok(strip(await ourList()) === strip(before), "JSON export -> import round-trips exactly");
  await page.setInputFiles("#otImport", TMP + "/our.csv");
  await page.waitForFunction(() => /Imported 0 tools \(3 already/.test(document.getElementById("otStatus").textContent));
  ok((await ourList()).length === 3, "importing again skips duplicates");
  await page.evaluate(() => localStorage.removeItem("ga-osi-our-tools-v1"));
  await page.reload({ waitUntil: "networkidle" });
  await page.setInputFiles("#otImport", TMP + "/our.csv");
  await page.waitForFunction(() => /Imported 3 tools/.test(document.getElementById("otStatus").textContent));
  ok(strip(await ourList()) === strip(before), "CSV export -> import round-trips exactly (guard removed)");
  fs.writeFileSync(TMP + "/bad.csv", "foo,bar\n1,2\n");
  await page.setInputFiles("#otImport", TMP + "/bad.csv");
  await page.waitForFunction(() => /Import failed/.test(document.getElementById("otStatus").textContent));
  ok((await ourList()).length === 3, "a wrong file is refused without changing the list");
  // remove the nasty one
  const nastyPos = (await page.$$eval("#otList tbody tr", r => r.map(x => x.textContent))).findIndex(t => /HYPERLINK/.test(t));
  await page.click(`#otList tbody tr:nth-child(${nastyPos + 1}) .ot-del`);
  ok((await ourList()).length === 2 && !(/HYPERLINK/.test(await page.textContent("#otList"))), "Remove deletes a tool");
  // print
  await page.emulateMedia({ media: "print" });
  ok(await page.isVisible("#otList table") && !(await page.isVisible("#otAdd")) && !(await page.isVisible(".ot-edit")) && !(await page.isVisible("#otSugg")), "print: Our tools table shown, buttons and suggestions hidden");
  ok(/added by you/.test(await page.textContent("#msCover")), "print: coverage marks our tools 'added by you'");
  await page.pdf({ path: SHOTS + "/tools-handout-our-tools.pdf", landscape: true, format: "A4", printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: "screen" });

  /* ---- game ---- */
  await page.goto(BASE + "/matrix/game", { waitUntil: "networkidle" });
  await page.evaluate(() => localStorage.removeItem("ga-osi-game-v1"));
  await page.reload({ waitUntil: "networkidle" });
  ok(await page.locator("button[data-ours='1']").count() === 1 && /2 of Our tools/.test(await page.textContent(".g-seg__note")), "setup offers 'Use our tools too' and shows how many are saved");
  await page.click("button[data-ours='1']");
  ok(await page.getAttribute("button[data-ours='1']", "aria-pressed") === "true", "Use our tools too switched on");
  await page.screenshot({ path: SHOTS + "/game-setup-our-tools.png" });
  await page.click("#gStart");
  await page.keyboard.press("PageDown");
  for (let i = 0; i < 8; i++) await page.keyboard.press("s");
  ok((await page.textContent("#gWhere")) === "Half time", "skipped through round 1");
  await page.keyboard.press("PageDown"); await page.keyboard.press("PageDown");
  for (let i = 0; i < 4; i++) await page.keyboard.press("s");
  ok(/Round 2 · 5\/8/.test(await page.textContent("#gWhere")) && /admin password/i.test(await page.textContent("#gCardTitle")), "round 2 card 5: reused admin password (L5)");
  const ours = await page.$$eval(".g-ours", e => e.map(x => x.querySelector(".g-letter").textContent + " " + x.querySelector(".g-tool__n").textContent));
  ok(ours.length === 2 && ours[0].startsWith("E ") && ours.some(x => /Cisco ISE/.test(x)) && ours.some(x => /Cisco Duo/.test(x)), "our L5 tools appear as extra choices E/F (" + ours.join("; ") + ")");
  await page.keyboard.press("ArrowRight");
  ok(await page.locator(".g-ours.is-ours .g-badge--ours").count() === 2, "on reveal our tools are marked 'Your call', not wrong");
  await page.screenshot({ path: SHOTS + "/game-round2-our-tools.png" });
  // accept another tool
  ok(await page.isVisible("#gAccOpen"), "'Accept another tool' button after reveal");
  await page.keyboard.press("a");
  ok(await page.evaluate(() => document.activeElement.id) === "gAccName", "A opens the panel and focuses the tool name");
  await page.click("button[data-accteam='1']");
  await page.fill("#gAccName", "Okta");
  ok(await page.locator("#gToolNames option[value='Okta']").count() === 1 && await page.locator("#gToolNames option[value='Cisco ISE']").count() === 1, "name suggestions include Our tools, Microsoft tools and common vendors");
  await page.screenshot({ path: SHOTS + "/game-accept-tool.png" });
  await page.keyboard.press("Enter");
  const minis = async () => (await page.$$eval("#gMini b", b => b.map(x => +x.textContent))).join(",");
  ok(await minis() === "0,2,0,0" && /Blue team.*named Okta/.test(await page.textContent(".g-accepted")), "accepted: Blue team +2 for naming Okta (" + await minis() + ")");
  await page.click(".g-accepted .g-x");
  ok(await minis() === "0,0,0,0" && await page.locator(".g-accepted").count() === 0, "undo removes the accepted tool and points");
  await page.click("#gAccOpen"); await page.click("button[data-accteam='1']"); await page.fill("#gAccName", "Okta"); await page.click("#gAccOk");
  await page.keyboard.press("ArrowRight"); await page.keyboard.press("ArrowRight");
  await page.keyboard.press("a"); await page.click("button[data-accteam='3']"); await page.fill("#gAccName", "Physical shredding service"); await page.keyboard.press("Enter");
  ok(await minis() === "0,2,0,2", "a second accepted tool on another card");
  await page.reload({ waitUntil: "networkidle" });
  ok(await minis() === "0,2,0,2" && await page.locator(".g-accepted li").count() === 1, "accepted tools persist after reload");
  await page.screenshot({ path: SHOTS + "/game-accepted-list.png" });
  await page.keyboard.press("End");
  const cov = await page.textContent(".g-cover");
  ok(/Okta named in the game/.test(cov) && /Cisco ISE added by you/.test(cov), "tool list screen shows our tools and the tools the room named");
  ok(/Our tools and tools the room named/.test(await page.textContent(".g-screen")), "final tool list has an 'Our tools and tools the room named' table");
  await page.screenshot({ path: SHOTS + "/game-final-tools-ours.png", fullPage: true });
  await page.keyboard.press("ArrowLeft");
  const named = await page.$$eval(".g-named__list li", l => l.map(x => x.textContent));
  ok(named.length === 2 && /Okta/.test(named.join()) && /reused/i.test(named.join()), "final screen lists 'Tools the room named' with their cards");
  await page.screenshot({ path: SHOTS + "/game-final-named.png", fullPage: true });
  await page.click(".g-named__list li:first-child .g-named__add");
  ok((await ourList()).some(t => t.name === "Okta" && t.layers.join() === "5") && /In Our tools/.test(await page.textContent(".g-named__list li:first-child")), "'Save to Our tools' adds Okta at the card's layer (L5)");
  await page.keyboard.press("ArrowRight");
  ok(/Okta added by you/.test(await page.textContent(".g-cover")), "saved tool now shows as 'added by you'");
  await page.emulateMedia({ media: "print" });
  const pr = await page.textContent("#gPrintView");
  ok(/Okta/.test(pr) && /Cisco ISE/.test(pr) && /Physical shredding service/.test(pr) && /Microsoft Sentinel/.test(pr), "printed handout includes our tools, named tools and the Microsoft set");
  await page.pdf({ path: SHOTS + "/game-tool-handout-our-tools.pdf", landscape: true, format: "A4", printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: "screen" });
  ok((await page.evaluate(() => window.__csp)).length === 0, "no CSP violations");
  ok(errs.length === 0, "no console errors " + JSON.stringify(errs));

  /* ---- phone ---- */
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const pp = await phone.newPage();
  await pp.goto(BASE + "/matrix/tools", { waitUntil: "networkidle" });
  await pp.evaluate(t => localStorage.setItem("ga-osi-our-tools-v1", t), JSON.stringify(await ourList()));
  await pp.reload({ waitUntil: "networkidle" });
  ok(await pp.evaluate(() => document.documentElement.scrollWidth) <= 392, "phone: tool list with Our tools fits");
  await pp.screenshot({ path: SHOTS + "/phone-tools-our-tools.png", fullPage: false });
  await pp.tap("#otAdd");
  ok(await pp.isVisible("#otDialog") && await pp.evaluate(() => document.getElementById("otDialog").getBoundingClientRect().width) <= 390, "phone: add-tool form fits");
  await pp.screenshot({ path: SHOTS + "/phone-add-tool-form.png" });
  await browser.close();
  console.log(fails ? "OURTOOLS-E2E-FAILED " + fails : "OURTOOLS-E2E-PASSED");
  process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(2); });
